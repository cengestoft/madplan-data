#!/usr/bin/env python3
"""Safety guard + report for a CANDIDATE history import (never publishes anything).

Compares the committed history (before) with a freshly built candidate (after). It stops the run (exit 1) when
  * the candidate is empty/invalid, not verified_only, not aggregate-only, over 12 MB or lacks the dagligepriser.dk credit,
  * previously verified history disappears (a verified key lost, or months lost for a verified key) without a documented reason,
  * the identity registry shrinks, or the public verification file contains fields that could carry raw text.
Its report holds COUNTS and normalized product keys only (our own offer data) — never raw product names — because this repository
is public and Actions logs/artifacts are readable by anyone.

Usage: python3 scripts/history_import_guard.py --before-dir . --after-dir OUT [--report OUT/report.md] [--diff OUT/diff.json]
Documented exceptions: data_sources/history_expected_changes.json {"allowed_losses":[{"key":"...","reason":"..."}]}
"""
from __future__ import annotations
import argparse, datetime as dt, json, sys
from collections import defaultdict
from pathlib import Path

MAX_BYTES = 12 * 1024 * 1024
ALLOWED_KEY_FIELDS = {"active", "status", "offer_names", "raw_products", "methods", "conflict_fields", "missing_fields",
                      "manual_decisions", "manual_decisions_blocked", "months"}
MIN_GRAPH_MONTHS = 3  # same rule as the app worker


def load(path, default=None):
    p = Path(path)
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else default


def months_by_key(hist):
    out = defaultdict(set)
    for r in hist.get("records", []):
        out[r["normalized_product_key"]].add(r["month"])
    return out


def metrics(hist, ver, decisions=None):
    months = months_by_key(hist)
    keys = (ver or {}).get("keys", {})
    st = defaultdict(int)
    raw_rejected = 0
    applied = blocked = 0
    for v in keys.values():
        st[v.get("status")] += 1
        raw_rejected += (v.get("raw_products") or {}).get("rejected", 0)
        applied += v.get("manual_decisions", 0)
        blocked += v.get("manual_decisions_blocked", 0)
    verified_decisions = sum(1 for d in (decisions or {}).get("decisions", []) if d.get("decision") == "verified")
    return {"rows": len(hist.get("records", [])), "history_keys": len(months),
            "verified_keys": st["verified"], "review_required_keys": st["review_required"], "rejected_keys": st["rejected"],
            "no_candidate_keys": st["no_candidate"], "rejected_raw_products": raw_rejected,
            "graph_keys": sum(1 for m in months.values() if len(m) >= MIN_GRAPH_MONTHS),
            "approvals_in_file": verified_decisions, "approvals_applied": applied, "approvals_blocked_no_evidence": blocked,
            "approvals_not_seen_in_raw": max(0, verified_decisions - applied - blocked)}


def allowed_losses(doc):
    return {x["key"] for x in (doc or {}).get("allowed_losses", []) if x.get("key") and str(x.get("reason") or "").strip()}


def _parse(ts):
    try:
        d = dt.datetime.fromisoformat(str(ts))
        return d if d.tzinfo else d.replace(tzinfo=dt.timezone.utc)
    except Exception:
        return None


def check(before_hist, before_ver, after_hist, after_ver, after_size, before_registry, after_registry, allowed=None, started_at=None):
    """Returns a list of blocking problems (empty = OK)."""
    bad = []
    allowed = allowed or set()
    if not after_hist or not after_hist.get("records"):
        return ["candidate history is empty or invalid"]
    if after_hist.get("verified_only") is not True:
        bad.append("candidate is not verified_only")
    if after_hist.get("raw_data_included") is not False:
        bad.append("candidate does not declare raw_data_included=false")
    if after_size >= MAX_BYTES:
        bad.append(f"candidate is {after_size} bytes (limit {MAX_BYTES})")
    if "dagligepriser.dk" not in str(after_hist.get("credit", "")) or any(r.get("source") != "dagligepriser.dk" for r in after_hist["records"]):
        bad.append("credit to dagligepriser.dk is missing")
    if not after_ver or not after_ver.get("keys"):
        return bad + ["candidate verification file is missing or empty"]
    if started_at is not None:  # both files must have been written by THIS run (never a leftover from an earlier run)
        for name, doc in (("verification file", after_ver), ("history file", after_hist)):
            ts = _parse(doc.get("generated_at"))
            if ts is None or ts < started_at:
                bad.append(f"{name} was not generated by this import run")
    if (after_ver or {}).get("raw_data_included") is not False:
        bad.append("verification file does not declare raw_data_included=false")
    for k, v in after_ver["keys"].items():
        extra = set(v) - ALLOWED_KEY_FIELDS
        if extra:
            bad.append(f"verification key carries unexpected fields {sorted(extra)} (possible raw text)"); break
    if sum(1 for v in after_ver["keys"].values() if v.get("status") == "verified") == 0:
        bad.append("candidate has no verified keys")
    # verified history must not disappear without a documented reason
    b_keys, a_keys = (before_ver or {}).get("keys", {}), after_ver["keys"]
    bm, am = months_by_key(before_hist or {}), months_by_key(after_hist)
    lost = sorted(k for k, v in b_keys.items() if v.get("status") == "verified" and a_keys.get(k, {}).get("status") != "verified" and k not in allowed)
    if lost:
        bad.append(f"{len(lost)} previously verified keys are no longer verified")
    shrunk = sorted(k for k, m in bm.items() if k in b_keys and b_keys[k].get("status") == "verified" and not m <= am.get(k, set()) and k not in allowed)
    if shrunk:
        bad.append(f"{len(shrunk)} verified keys lost history months")
    if set(before_registry or {}) - set(after_registry or {}):
        bad.append("identity registry lost keys")
    return bad


def diff(before_hist, before_ver, after_hist, after_ver):
    bk = {k for k, v in (before_ver or {}).get("keys", {}).items() if v.get("status") == "verified"}
    ak = {k for k, v in after_ver.get("keys", {}).items() if v.get("status") == "verified"}
    bg = {k for k, m in months_by_key(before_hist or {}).items() if len(m) >= MIN_GRAPH_MONTHS}
    ag = {k for k, m in months_by_key(after_hist).items() if len(m) >= MIN_GRAPH_MONTHS}
    return {"verified_added": sorted(ak - bk)[:200], "verified_added_count": len(ak - bk), "verified_lost": sorted(bk - ak)[:200],
            "verified_lost_count": len(bk - ak), "graph_keys_added_count": len(ag - bg), "graph_keys_lost_count": len(bg - ag),
            "graph_keys_lost": sorted(bg - ag)[:200]}


def report_md(b, a, d, problems):
    rows = [("Historikrækker", "rows"), ("Historiknøgler", "history_keys"), ("Verificerede nøgler", "verified_keys"),
            ("Nøgler med graf (≥3 måneder)", "graph_keys"), ("Nøgler review_required", "review_required_keys"),
            ("Afviste nøgler", "rejected_keys"), ("Afviste råprodukter (match)", "rejected_raw_products"), ("Nøgler uden kandidat", "no_candidate_keys")]
    lines = ["## Kandidat-import (ingen publicering)", "", "| | Før | Efter |", "|---|---:|---:|"]
    lines += [f"| {t} | {b[k]} | {a[k]} |" for t, k in rows]
    lines += ["", "### Foreløbige godkendelser mod faktisk rådata",
              f"- i filen: {a['approvals_in_file']}", f"- anvendt (dokumenteret evidens): {a['approvals_applied']}",
              f"- ikke anvendt, evidens manglede/modsagde (forbliver review_required): {a['approvals_blocked_no_evidence']}",
              f"- ikke set i rådata: {a['approvals_not_seen_in_raw']}", "",
              f"Verificerede nøgler: +{d['verified_added_count']} / −{d['verified_lost_count']}. Grafnøgler: +{d['graph_keys_added_count']} / −{d['graph_keys_lost_count']}.", "",
              "Kreditering: dagligepriser.dk (kontrolleret).", ""]
    lines += ["### RESULTAT: " + ("STOP – " + "; ".join(problems) if problems else "OK (kun kandidat; intet er committet eller publiceret)")]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--before-dir", default="."); ap.add_argument("--after-dir", required=True)
    ap.add_argument("--report"); ap.add_argument("--diff")
    ap.add_argument("--started-at", help="ISO timestamp taken just before the import; candidate files older than this are rejected")
    ap.add_argument("--expected-changes", default="data_sources/history_expected_changes.json")
    a = ap.parse_args()
    bd, ad = Path(a.before_dir), Path(a.after_dir)
    bh, bv = load(bd / "monthly_price_history.json", {}), load(bd / "history_verification.json", {})
    ah_path = ad / "monthly_price_history.json"
    try:
        ah = load(ah_path); av = load(ad / "history_verification.json")
    except Exception:
        ah = av = None
    size = ah_path.stat().st_size if ah_path.exists() else 0
    breg = (load(bd / "data_sources/history_offer_identities.json", {}) or {}).get("keys", {})
    areg = (load(ad / "history_offer_identities.json", {}) or {}).get("keys", {})
    started = _parse(a.started_at) if a.started_at else None
    if a.started_at and started is None:
        raise SystemExit("ERROR: invalid --started-at")
    problems = check(bh, bv, ah, av, size, breg, areg, allowed_losses(load(bd / a.expected_changes)), started)
    if not (ad / "history_verification.json").exists():
        problems.append("history_verification.json was not generated by the import")
    decisions = load(bd / "data_sources/history_review_decisions.json", {})
    if ah and av:
        bm, am, dd = metrics(bh, bv, decisions), metrics(ah, av, decisions), diff(bh, bv, ah, av)
        md = report_md(bm, am, dd, problems)
        if a.diff: Path(a.diff).write_text(json.dumps({"before": bm, "after": am, **dd, "problems": problems}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    else:
        md = "## Kandidat-import\n\n### RESULTAT: STOP – " + "; ".join(problems) + "\n"
    if a.report: Path(a.report).write_text(md, encoding="utf-8")
    print(md)
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
